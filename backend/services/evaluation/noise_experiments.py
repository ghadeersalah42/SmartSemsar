"""Controlled Audio Quality, Noise Injection (e.g., 5 dB), and Phone Filter Experiments.

All modified audio generated by this script is EXPLICITLY labeled as
`SIMULATED / AUGMENTED` and saved under
`backend/services/data/evaluation/experiments/augmented_audio/`.
Original recordings in `backend/services/data/raw_calls/` and Human Ground Truth
files in `backend/services/data/evaluation/ground_truth/` are strictly read-only.

Purpose:
- Reproduce and empirically investigate:
  1. Why 5 dB additive noise might appear to outperform clean audio (or whether it does
     not under controlled active-speech-calibrated SNR across multiple random seeds).
  2. The effect of a telephony Phone Bandpass Filter (300-3400 Hz, plus 8 kHz narrowband
     resampling) on signal energy, VAD speech ratio, and ASR WER/CER, and whether a
     1.10% result is reproduced or explained by specific measurement conditions.

Usage:
    .venv/Scripts/python.exe backend/services/evaluation/noise_experiments.py
"""
