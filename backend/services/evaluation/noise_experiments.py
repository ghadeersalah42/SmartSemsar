def _build_speech_mask(n_samples: int, sr: int, vad_segments: list[dict[str, Any]]) -> np.ndarray:
    mask = np.zeros(n_samples, dtype=bool)
    for seg in vad_segments:
        s = max(0, min(n_samples, int(round(float(seg["start"]) * sr))))
        e = max(0, min(n_samples, int(round(float(seg["end"]) * sr))))
        if e > s:
            mask[s:e] = True
    return mask


def _generate_pink_noise(n_samples: int, rng: np.random.Generator) -> np.ndarray:
    """Generate 1/f pink noise via spectral shaping."""
    white = rng.standard_normal(n_samples)
    spec = np.fft.rfft(white)
    freqs = np.fft.rfftfreq(n_samples)
    scale = np.ones_like(freqs)
    scale[1:] = 1.0 / np.sqrt(freqs[1:])
    pink = np.fft.irfft(spec * scale, n=n_samples)
    pink = pink / (np.std(pink) + 1e-12)
    return pink.astype(np.float32)


def inject_noise_at_snr(
    audio: np.ndarray,
    sr: int,
    target_snr_db: float,
    *,
    noise_type: str = "white",
    seed: int = 42,
    speech_mask: Optional[np.ndarray] = None,
) -> tuple[np.ndarray, dict[str, Any]]:
    """Inject controlled noise calibrated to active-speech RMS (when VAD mask provided)."""
    rng = np.random.default_rng(seed)
    n = len(audio)
    if noise_type == "white":
        noise = rng.standard_normal(n).astype(np.float32)
    elif noise_type == "pink":
        noise = _generate_pink_noise(n, rng)
    else:
        raise ValueError(f"Unsupported noise_type: {noise_type}")

    if speech_mask is not None and np.any(speech_mask):
        ref_signal = audio[speech_mask]
        calibration_basis = "active_vad_speech_rms"
    else:
        ref_signal = audio
        calibration_basis = "full_file_rms"

    signal_rms = float(np.sqrt(np.mean(ref_signal ** 2)))
    noise_raw_rms = float(np.sqrt(np.mean(noise ** 2))) + 1e-12
    target_noise_rms = signal_rms / (10.0 ** (target_snr_db / 20.0))
    scaled_noise = noise * (target_noise_rms / noise_raw_rms)

    mixed = audio + scaled_noise
    clipped_before_norm = int(np.sum(np.abs(mixed) >= 0.99))
    mixed_clipped = np.clip(mixed, -0.999, 0.999).astype(np.float32)

    actual_noise_rms = float(np.sqrt(np.mean(scaled_noise ** 2))) + 1e-12
    actual_snr_db = 20.0 * math.log10(max(signal_rms, 1e-12) / actual_noise_rms)

    return mixed_clipped, {
        "is_simulated": True,
        "augmentation_type": f"additive_{noise_type}_noise",
        "target_snr_db": target_snr_db,
        "actual_injected_snr_db": round(actual_snr_db, 3),
        "calibration_basis": calibration_basis,
        "seed": seed,
        "active_speech_rms": round(signal_rms, 6),
        "injected_noise_rms": round(actual_noise_rms, 6),
        "clipped_samples_pre_clip": clipped_before_norm,
    }


def apply_phone_filter(
    audio: np.ndarray,
    sr: int,
    *,
    lowcut_hz: float = 300.0,
    highcut_hz: float = 3400.0,
    order: int = 4,
    downsample_8khz: bool = False,
) -> tuple[np.ndarray, dict[str, Any]]:
    """Simulate PSTN/telephony narrowband channel (300-3400 Hz bandpass, optional 8 kHz resample)."""
    nyq = 0.5 * sr
    sos = signal.butter(order, [lowcut_hz / nyq, highcut_hz / nyq], btype="bandpass", output="sos")
    filtered = signal.sosfiltfilt(sos, audio).astype(np.float32)

    if downsample_8khz and sr == 16000:
        # Downsample 16 kHz -> 8 kHz -> 16 kHz to simulate 8 kHz narrowband telephony sampling
        down = signal.resample_poly(filtered, up=1, down=2)
        filtered = signal.resample_poly(down, up=2, down=1)[: len(audio)].astype(np.float32)

    # Preserve RMS roughly without clipping
    peak = float(np.max(np.abs(filtered)))
    if peak > 0.99:
        filtered = (filtered / peak * 0.98).astype(np.float32)

    return filtered, {
        "is_simulated": True,
        "augmentation_type": "phone_filter_8khz_narrowband" if downsample_8khz else "phone_bandpass_300_3400hz",
        "lowcut_hz": lowcut_hz,
        "highcut_hz": highcut_hz,
        "butterworth_order": order,
        "zero_phase": True,
        "resampled_via_8khz": downsample_8khz,
    }


def run_experiments(
    call_id: str = "smartsemsar_rec1",
    *,
    seeds: tuple[int, ...] = (42, 123, 2026),
    run_groq: bool = True,
    run_local_small: bool = True,
) -> dict[str, Any]:
    EXPERIMENTS_DIR.mkdir(parents=True, exist_ok=True)
    AUGMENTED_AUDIO_DIR.mkdir(parents=True, exist_ok=True)

    wav_path = PROCESSED_AUDIO_DIR / f"{call_id}_standardized.wav"
    vad_path = VAD_DIR / f"{call_id}_vad.json"
    gt_path = GT_TRANSCRIPTS_DIR / f"{call_id}_gt_transcript.json"

    if not wav_path.exists():
        raise FileNotFoundError(f"Standardized WAV missing: {wav_path}. Run run_asr_and_audio_batch.py first.")
    if not gt_path.exists():
        raise FileNotFoundError(f"Ground truth transcript missing: {gt_path}")

    with open(gt_path, "r", encoding="utf-8") as f:
        gt_data = json.load(f)
    ref_text = gt_data["reference_transcript"]

    vad_segments = None
    if vad_path.exists():
        with open(vad_path, "r", encoding="utf-8") as f:
            vad_segments = json.load(f).get("speech_segments")

    audio, sr = sf.read(str(wav_path), dtype="float32")
    if audio.ndim > 1:
        audio = audio.mean(axis=1)
    speech_mask = _build_speech_mask(len(audio), sr, vad_segments) if vad_segments else None

    small_model = None
    if run_local_small:
        from faster_whisper import WhisperModel

        small_model = WhisperModel("small", device="cpu", compute_type="int8", local_files_only=True)

    # Define controlled experimental matrix
    conditions: list[tuple[str, Path, dict[str, Any]]] = []

    # 0. Real unmodified standardized baseline
    conditions.append((
        "baseline_original_real",
        wav_path,
        {"is_simulated": False, "augmentation_type": "none_original_recording"},
    ))

    # 1. Telephony Phone Filter (300-3400 Hz bandpass)
    pf_audio, pf_meta = apply_phone_filter(audio, sr, downsample_8khz=False)
    pf_path = AUGMENTED_AUDIO_DIR / f"{call_id}_SIMULATED_phone_bandpass_300_3400hz.wav"
    sf.write(pf_path, pf_audio, sr, subtype="PCM_16")
    conditions.append(("phone_bandpass_300_3400hz", pf_path, pf_meta))

    # 2. Telephony Phone Filter + 8 kHz narrowband resample
    pf8_audio, pf8_meta = apply_phone_filter(audio, sr, downsample_8khz=True)
    pf8_path = AUGMENTED_AUDIO_DIR / f"{call_id}_SIMULATED_phone_8khz_narrowband.wav"
    sf.write(pf8_path, pf8_audio, sr, subtype="PCM_16")
    conditions.append(("phone_8khz_narrowband", pf8_path, pf8_meta))

    # 3. White noise sweep (20, 10, 5, 0 dB) — multi-seed at 5 dB & 10 dB to check variance!
    for snr_db in (20, 10, 5, 0):
        cond_seeds = seeds if snr_db in (10, 5) else (seeds[0],)
        for sd in cond_seeds:
            noisy, n_meta = inject_noise_at_snr(
                audio, sr, snr_db, noise_type="white", seed=sd, speech_mask=speech_mask
            )
            cname = f"white_noise_{snr_db}db_seed{sd}"
            n_path = AUGMENTED_AUDIO_DIR / f"{call_id}_SIMULATED_{cname}.wav"
            sf.write(n_path, noisy, sr, subtype="PCM_16")
            conditions.append((cname, n_path, n_meta))

    # 4. Pink (ambient 1/f) noise at 10 dB and 5 dB (multi-seed at 5 dB)
    for snr_db in (10, 5):
        cond_seeds = seeds if snr_db == 5 else (seeds[0],)
        for sd in cond_seeds:
            noisy, n_meta = inject_noise_at_snr(
                audio, sr, snr_db, noise_type="pink", seed=sd, speech_mask=speech_mask
            )
            cname = f"pink_noise_{snr_db}db_seed{sd}"
            n_path = AUGMENTED_AUDIO_DIR / f"{call_id}_SIMULATED_{cname}.wav"
            sf.write(n_path, noisy, sr, subtype="PCM_16")
            conditions.append((cname, n_path, n_meta))

    # 5. Combined Phone Filter + 5 dB / 10 dB Pink Noise
    for snr_db in (10, 5):
        noisy_pf, n_meta = inject_noise_at_snr(
            pf8_audio, sr, snr_db, noise_type="pink", seed=seeds[0], speech_mask=speech_mask
        )
        n_meta["augmentation_type"] = f"phone_8khz_plus_pink_noise_{snr_db}db"
        cname = f"phone_8khz_plus_pink_{snr_db}db_seed{seeds[0]}"
        n_path = AUGMENTED_AUDIO_DIR / f"{call_id}_SIMULATED_{cname}.wav"
        sf.write(n_path, noisy_pf, sr, subtype="PCM_16")
        conditions.append((cname, n_path, n_meta))

    # Evaluate every condition
    results: list[dict[str, Any]] = []
    for cname, cpath, cmeta in conditions:
        print(f"Evaluating condition: {cname} (simulated={cmeta['is_simulated']})")
        aq = analyze_audio_quality(cpath, vad_segments=vad_segments)
        entry: dict[str, Any] = {
            "condition": cname,
            "audio_path": str(cpath),
            "is_simulated": cmeta["is_simulated"],
            "augmentation": cmeta,
            "audio_quality": aq,
        }

        if run_groq:
            try:
                _meta, _segs, hyp_groq = transcribe_with_groq_whisper(
                    cpath, model_name="whisper-large-v3-turbo"
                )
                w_g = compute_wer(ref_text, hyp_groq, normalize=True)
                c_g = compute_cer(ref_text, hyp_groq, normalize=True)
                entry["groq_whisper_large_v3_turbo"] = {
                    "wer": w_g["wer"],
                    "cer": c_g["cer"],
                    "wer_pct": round(w_g["wer"] * 100.0, 2),
                    "cer_pct": round(c_g["cer"] * 100.0, 2),
                    "wer_details": w_g,
                    "cer_details": c_g,
                    "hypothesis_transcript": hyp_groq,
                }
            except Exception as exc:
                entry["groq_whisper_large_v3_turbo"] = {"error": f"{type(exc).__name__}: {exc}"}

        if run_local_small and small_model is not None:
            try:
                _info, _segs, hyp_small = pipeline_transcribe(cpath, "cpu", whisper_model=small_model)
                w_s = compute_wer(ref_text, hyp_small, normalize=True)
                c_s = compute_cer(ref_text, hyp_small, normalize=True)
                entry["faster_whisper_small"] = {
                    "wer": w_s["wer"],
                    "cer": c_s["cer"],
                    "wer_pct": round(w_s["wer"] * 100.0, 2),
                    "cer_pct": round(c_s["cer"] * 100.0, 2),
                    "wer_details": w_s,
                    "cer_details": c_s,
                    "hypothesis_transcript": hyp_small,
                }
            except Exception as exc:
                entry["faster_whisper_small"] = {"error": f"{type(exc).__name__}: {exc}"}

        results.append(entry)

    # Compute deltas relative to baseline for clear comparison
    baseline = next(r for r in results if r["condition"] == "baseline_original_real")
    for model_key in ("groq_whisper_large_v3_turbo", "faster_whisper_small"):
        base_m = baseline.get(model_key, {})
        if "wer" in base_m:
            for r in results:
                cur = r.get(model_key, {})
                if "wer" in cur:
                    cur["wer_delta_vs_baseline_pct"] = round((cur["wer"] - base_m["wer"]) * 100.0, 2)
                    cur["cer_delta_vs_baseline_pct"] = round((cur["cer"] - base_m["cer"]) * 100.0, 2)

    # Aggregate multi-seed groups (e.g., white_noise_5db, pink_noise_5db)
    def _group_stats(prefix: str, model_key: str) -> Optional[dict[str, Any]]:
        matched = [
            r[model_key]
            for r in results
            if r["condition"].startswith(prefix) and model_key in r and "wer" in r[model_key]
        ]
        if not matched:
            return None
        wers = [m["wer"] for m in matched]
        cers = [m["cer"] for m in matched]
        return {
            "n_runs": len(matched),
            "mean_wer_pct": round(float(np.mean(wers)) * 100.0, 2),
            "std_wer_pct": round(float(np.std(wers)) * 100.0, 2),
            "min_wer_pct": round(float(np.min(wers)) * 100.0, 2),
            "max_wer_pct": round(float(np.max(wers)) * 100.0, 2),
            "mean_cer_pct": round(float(np.mean(cers)) * 100.0, 2),
            "std_cer_pct": round(float(np.std(cers)) * 100.0, 2),
        }

    grouped_summary: dict[str, Any] = {}
    for prefix in (
        "baseline_original_real",
        "phone_bandpass_300_3400hz",
        "phone_8khz_narrowband",
        "white_noise_20db",
        "white_noise_10db",
        "white_noise_5db",
        "white_noise_0db",
        "pink_noise_10db",
        "pink_noise_5db",
        "phone_8khz_plus_pink_10db",
        "phone_8khz_plus_pink_5db",
    ):
        grouped_summary[prefix] = {
            "groq_whisper_large_v3_turbo": _group_stats(prefix, "groq_whisper_large_v3_turbo"),
            "faster_whisper_small": _group_stats(prefix, "faster_whisper_small"),
        }

    report = {
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "call_id": call_id,
        "ground_truth_source": str(gt_path),
        "reference_word_count": len(ref_text.split()),
        "original_experiment_artifacts_found_in_repo": False,
        "reproduction_note": (
            "No prior 5 dB noise or Phone Filter (1.10%) scripts/results existed in the repository. "
            "These controlled experiments were reproduced on smartsemsar_rec1 (the only call with "
            "completed human Ground Truth) using active-VAD-speech RMS SNR calibration across "
            "multiple seeds and explicit SIMULATED/AUGMENTED labeling."
        ),
        "seeds": list(seeds),
        "grouped_summary": grouped_summary,
        "conditions": results,
    }
    out_name = (
        "noise_and_phone_filter_results.json"
        if call_id == "smartsemsar_rec1"
        else f"noise_and_phone_filter_results_{call_id}.json"
    )
    save_json(EXPERIMENTS_DIR / out_name, report)
    return report


def main(argv: Optional[list[str]] = None) -> int:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser(description="Run controlled noise & phone-filter experiments.")
    parser.add_argument("--call-id", default="smartsemsar_rec1")
    parser.add_argument("--skip-groq", action="store_true")
    parser.add_argument("--skip-small", action="store_true")
    args = parser.parse_args(argv)

    run_experiments(
        call_id=args.call_id,
        run_groq=not args.skip_groq,
        run_local_small=not args.skip_small,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
